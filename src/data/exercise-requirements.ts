import type { ExerciseGroup } from '../data/exercises';

export type RequirementProfile = {
  kind: 'contract' | 'cadet' | 'conscript';
  sex: 'male' | 'female';
  age?: number;
  category?: 1 | 2 | 3;
  course?: 1 | 2 | 3;
  conscriptCount?: 3 | 4;
};
export type RequirementBlock = {
  title: string;
  count: number;
  description: string;
  alternatives?: string[];
  groups: ExerciseGroup[];
  special?: boolean;
};
export type ExerciseRequirements = {
  supported: boolean;
  total: number | null;
  blocks: RequirementBlock[];
  note: string;
};

const block=(title:string,count:number,description:string,groups:ExerciseGroup[],alternatives?:string[],special=false):RequirementBlock=>({title,count,description,groups,alternatives,special});

export function getExerciseRequirements(p:RequirementProfile):ExerciseRequirements {
  if(p.kind==='conscript') {
    if(p.conscriptCount!==3&&p.conscriptCount!==4) return {supported:false,total:null,blocks:[],note:'Для военнослужащих по призыву количество — 3 или 4 упражнения в зависимости от подразделения. Уточни установленный для подразделения вариант.'};
    return {supported:true,total:p.conscriptCount,blocks:[block('Комплект проверки',p.conscriptCount,'Приказ устанавливает 3 или 4 упражнения в зависимости от подразделения. Самостоятельно определить вариант только по категории службы нельзя.',['Сила','Быстрота','Выносливость','Ловкость','Ускоренное передвижение','Преодоление препятствий','Рукопашный бой','Метание','Военно-прикладное плавание','Специальные приёмы и действия'])],note:'Приказ не задаёт единый для всех призывников набор из 3 или 4 упражнений: решающим является подразделение, в котором проходит службу военнослужащий.'};
  }
  if(p.kind==='cadet') {
    if(p.course!==1&&p.course!==2&&p.course!==3)return {supported:false,total:null,blocks:[],note:'Укажи курс обучения.'};
    if(p.course===1)return {supported:true,total:4,blocks:[
      block('Общие физические упражнения',3,'По одному упражнению на быстроту или ловкость, силу и выносливость.',['Быстрота','Ловкость','Сила','Выносливость'],['Быстрота ИЛИ ловкость + сила + выносливость']),
      block('Специальное физическое упражнение',1,'Одно СФУ из программы обучения курсанта.',['Ускоренное передвижение','Преодоление препятствий','Рукопашный бой','Метание','Военно-прикладное плавание','Специальные приёмы и действия'],undefined,true),
    ],note:'Первый курс: всего 4 упражнения — 3 ОФУ (быстрота или ловкость, сила, выносливость) и 1 СФУ.'};
    return {supported:true,total:5,blocks:[
      block('Общие физические упражнения',3,'Вариант 1: быстрота, сила, выносливость. Вариант 2: быстрота, сила, ловкость.',['Быстрота','Сила','Выносливость','Ловкость'],['Быстрота + сила + выносливость','Быстрота + сила + ловкость']),
      block('Специальные физические упражнения',2,'Два СФУ из программы обучения курсанта.',['Ускоренное передвижение','Преодоление препятствий','Рукопашный бой','Метание','Военно-прикладное плавание','Специальные приёмы и действия'],undefined,true),
    ],note:'Второй и последующие курсы: всего 5 упражнений — 3 ОФУ и 2 СФУ.'};
  }
  if(!Number.isInteger(p.age)||p.age!<18)return {supported:false,total:null,blocks:[],note:'Укажи полный возраст на дату проверки.'};
  const age=p.age!;
  if(p.sex==='male') {
    const group=age<25?1:age<30?2:age<35?3:age<40?4:age<45?5:age<50?6:age<55?7:age<60?8:9;
    if(group<=6) {
      if(p.category!==1&&p.category!==2&&p.category!==3)return {supported:false,total:null,blocks:[],note:'Для военнослужащего мужчины по контракту до 50 лет укажи категорию 1, 2 или 3 по приложению № 6.'};
      if(p.category===1)return {supported:true,total:4,blocks:[
        block('Два общих физических упражнения',2,'Выбери один из трёх вариантов сочетания: быстрота/ловкость + сила; быстрота/ловкость + выносливость; сила + выносливость.',['Быстрота','Ловкость','Сила','Выносливость'],['Быстрота или ловкость + сила','Быстрота или ловкость + выносливость','Сила + выносливость']),
        block('Специальные физические упражнения',2,'Два СФУ по программе подготовки подразделения.',['Ускоренное передвижение','Преодоление препятствий','Рукопашный бой','Метание','Военно-прикладное плавание','Специальные приёмы и действия'],undefined,true),
      ],note:'Мужчины по контракту, возрастные группы 1–6, категория 1: 4 упражнения — 2 ОФУ и 2 СФУ.'};
      if(p.category===2)return {supported:true,total:3,blocks:[
        block('Два общих физических упражнения',2,'Выбери один из трёх вариантов сочетания: быстрота/ловкость + сила; быстрота/ловкость + выносливость; сила + выносливость.',['Быстрота','Ловкость','Сила','Выносливость'],['Быстрота или ловкость + сила','Быстрота или ловкость + выносливость','Сила + выносливость']),
        block('Специальное физическое упражнение',1,'Одно СФУ по программе подготовки подразделения.',['Ускоренное передвижение','Преодоление препятствий','Рукопашный бой','Метание','Военно-прикладное плавание','Специальные приёмы и действия'],undefined,true),
      ],note:'Мужчины по контракту, возрастные группы 1–6, категория 2: 3 упражнения — 2 ОФУ и 1 СФУ.'};
      return {supported:true,total:3,blocks:[
        block('Быстрота или ловкость',1,'Одно ОФУ на быстроту или ловкость.',['Быстрота','Ловкость'],['Быстрота ИЛИ ловкость']),
        block('Сила',1,'Одно ОФУ на силу.',['Сила']),
        block('Выносливость',1,'Одно ОФУ на выносливость.',['Выносливость']),
      ],note:'Мужчины по контракту, возрастные группы 1–6, категория 3: 3 ОФУ — быстрота или ловкость, сила, выносливость.'};
    }
    return {supported:true,total:2,blocks:[
      block('Одно упражнение на выбор',1,'Выбери одно ОФУ на быстроту, ловкость ИЛИ силу.',['Быстрота','Ловкость','Сила'],['Быстрота ИЛИ ловкость ИЛИ сила']),
      block('Выносливость',1,'Одно ОФУ на выносливость.',['Выносливость']),
    ],note:'Мужчины по контракту, возрастные группы 7–9: 2 ОФУ — одно на быстроту, ловкость или силу и одно на выносливость. Категория 1–3 не меняет этот набор.'};
  }
  const group=age<25?1:age<30?2:age<35?3:age<40?4:age<45?5:6;
  if(group<=5)return {supported:true,total:3,blocks:[
    block('Быстрота или ловкость',1,'Одно ОФУ на быстроту или ловкость.',['Быстрота','Ловкость'],['Быстрота ИЛИ ловкость']),
    block('Сила',1,'Одно ОФУ на силу.',['Сила']),
    block('Выносливость',1,'Одно ОФУ на выносливость.',['Выносливость']),
  ],note:'Военнослужащие женского пола, возрастные группы 1–5: 3 ОФУ — быстрота или ловкость, сила, выносливость.'};
  return {supported:true,total:2,blocks:[
    block('Одно упражнение на выбор',1,'Одно ОФУ на быстроту, ловкость ИЛИ силу.',['Быстрота','Ловкость','Сила'],['Быстрота ИЛИ ловкость ИЛИ сила']),
    block('Выносливость',1,'Одно ОФУ на выносливость.',['Выносливость']),
  ],note:'Военнослужащие женского пола, возрастная группа 6 и 7 (50 лет и старше): 2 ОФУ — одно на быстроту, ловкость или силу и одно на выносливость.'};
}
